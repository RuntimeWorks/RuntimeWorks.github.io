// Writes src/styles/tokens.css from three sources and nothing typed by hand:
// - colour: Radix's own custom-palette generator (scripts/vendor/radix, unchanged), fed the brand's two colours;
// - type and space: Utopia's calculator (utopia-core, Clearleft) with the defaults of utopia.fyi;
// - motion: IBM Carbon's duration and easing tokens.
// Run: npx tsx scripts/gen-tokens.ts (the build runs it first).
import fs from "node:fs"
import path from "node:path"
import Color from "colorjs.io"
import { calculateSpaceScale, calculateTypeScale } from "utopia-core"
import { generateRadixColors } from "./vendor/radix/generate-radix-colors.ts"
import { getColorScaleCss } from "./vendor/radix/utils.ts"
import { brand } from "../src/data/brand.ts"

const out = path.resolve(import.meta.dirname, "../src/styles/tokens.css")

// Colour. accent = the logo's navy; gray = Radix's own sand step 9, so the generator returns Radix sand;
// backgrounds = the brand's paper in light and Radix's default custom background in dark.
const light = generateRadixColors({ appearance: "light", accent: brand.colors.accent, gray: brand.colors.gray, background: brand.colors.backgroundLight })
const dark = generateRadixColors({ appearance: "dark", accent: brand.colors.accent, gray: brand.colors.gray, background: brand.colors.backgroundDark })

// Text on step 9. Radix picks white unless white's APCA contrast is under Lc 40, then a dark text colour from the
// step's own hue. WCAG 2.2 is the law and outranks APCA (SPEC.md §9), so white must also reach 4.5:1; when it
// doesn't, use Radix's own dark text formula (oklch 0.25, chroma max(0.08 C, 0.04), the same hue).
const onStep9 = (step9: string) => {
  const bg = new Color(step9).to("oklch")
  if (new Color("white").contrastWCAG21(bg) >= 4.5) return "#fff"
  const [, C, H] = bg.coords
  return new Color("oklch", [0.25, Math.max(0.08 * C, 0.04), H]).toString({ format: "hex" })
}
light.accentContrast = onStep9(light.accentScale[8])
dark.accentContrast = onStep9(dark.accentScale[8])

const scaleCss = (c: typeof light, isDarkMode: boolean) =>
  ["accent", "gray"].map((name) =>
    getColorScaleCss({
      isDarkMode,
      name,
      scale: name === "accent" ? c.accentScale : c.grayScale,
      scaleWideGamut: name === "accent" ? c.accentScaleWideGamut : c.grayScaleWideGamut,
      scaleAlpha: name === "accent" ? c.accentScaleAlpha : c.grayScaleAlpha,
      scaleAlphaWideGamut: name === "accent" ? c.accentScaleAlphaWideGamut : c.grayScaleAlphaWideGamut,
      contrast: name === "accent" ? c.accentContrast : "#fff",
      surface: name === "accent" ? c.accentSurface : c.graySurface,
      surfaceWideGamut: name === "accent" ? c.accentSurfaceWideGamut : c.graySurfaceWideGamut,
    }),
  ).join("\n\n")

// Radix writes dark mode under a .dark class; this site follows the visitor's system setting instead.
const lightCss = `${scaleCss(light, false).replaceAll(":root, .light, .light-theme", ":root")}\n\n:root {\n  --color-background: ${light.background};\n  color-scheme: light dark;\n}`
const darkCss = `@media (prefers-color-scheme: dark) {\n${scaleCss(dark, true).replaceAll(".dark, .dark-theme", ":root")}\n\n:root {\n  --color-background: ${dark.background};\n}\n}`

// Type: Utopia's default calculator settings (utopia.fyi/type/calculator): 18 px at 320 px wide on a 1.2 scale,
// 20 px at 1240 px on a 1.25 scale. Labels in Tailwind's names so the utilities read text-base, text-xl and so on.
const typeConfig = { minWidth: 320, maxWidth: 1240, minFontSize: 18, maxFontSize: 20, minTypeScale: 1.2, maxTypeScale: 1.25, negativeSteps: 2, positiveSteps: 5, labelStyle: "tailwind" as const }
const type = calculateTypeScale(typeConfig)
for (const s of type) if (s.wcagViolation) throw new Error(`Utopia type step ${s.label} fails WCAG 1.4.4 resize between ${s.wcagViolation.from} and ${s.wcagViolation.to} px`)
// Line heights: Tailwind CSS 4's defaults for the same names (leading falls as size grows).
const leading: Record<string, string> = { xs: "calc(1 / 0.75)", sm: "calc(1.25 / 0.875)", base: "calc(1.5 / 1)", lg: "calc(1.75 / 1.125)", xl: "calc(1.75 / 1.25)", "2xl": "calc(2 / 1.5)", "3xl": "calc(2.25 / 1.875)", "4xl": "calc(2.5 / 2.25)", "5xl": "1" }
const typeCss = type.map((s) => `  --text-${s.label}: ${s.clamp};\n  --text-${s.label}--line-height: ${leading[s.label] ?? "1.1"};`).join("\n")

// Space: Utopia's default space calculator (utopia.fyi/space/calculator), same viewports and base sizes.
const space = calculateSpaceScale({ minWidth: 320, maxWidth: 1240, minSize: 18, maxSize: 20, negativeSteps: [0.75, 0.5, 0.25], positiveSteps: [1.5, 2, 3, 4, 6], customSizes: ["s-l", "m-2xl", "l-3xl"] })
const spaceCss = [...space.sizes, ...space.oneUpPairs, ...space.customPairs].map((s) => `  --space-${s.label}: ${s.clamp};`).join("\n")

const css = `/* Generated by scripts/gen-tokens.ts. Do not edit; change src/data/brand.ts and rebuild. */

${lightCss}

${darkCss}

/* Utopia fluid type (Tailwind names) and space. */
:root {
${spaceCss}
}

@theme {
${typeCss}
  /* IBM Carbon motion: fast-01, fast-02, moderate-02 and the productive-standard curve. */
  --duration-fast: 110ms;
  --duration-moderate: 150ms;
  --duration-slow: 240ms;
  --ease-productive: cubic-bezier(0.2, 0, 0.38, 0.9);
}
`
fs.writeFileSync(out, css)
console.log(`tokens: ${type.length} type steps, ${space.sizes.length + space.oneUpPairs.length + space.customPairs.length} space sizes, accent ${light.accentScale[8]} / ${dark.accentScale[8]} -> ${path.relative(process.cwd(), out)}`)
